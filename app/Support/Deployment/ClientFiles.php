<?php

namespace App\Support\Deployment;

use Dotenv\Dotenv;
use Illuminate\Filesystem\Filesystem;
use RuntimeException;

/**
 * Reads and writes client deployment files in deployments/<code>/:
 *
 * - <code>.env: non-secret settings (client code, institution type, name,
 *   URL, receipt prefix, module overrides, infrastructure endpoints);
 * - <code>.env.secure: secrets (APP_KEY and the client's database
 *   credentials).
 */
class ClientFiles
{
    public function __construct(private Filesystem $files) {}

    public function root(): string
    {
        return rtrim((string) config('edunexus.provisioning.deployments_path'), '/');
    }

    public function directory(string $code): string
    {
        return $this->root().'/'.$code;
    }

    public function settingsPath(string $code): string
    {
        return $this->directory($code).'/'.ClientEnvironment::settingsFile($code);
    }

    public function secretsPath(string $code): string
    {
        return $this->directory($code).'/'.ClientEnvironment::secretsFile($code);
    }

    public function exists(string $code): bool
    {
        return $this->files->isDirectory($this->directory($code));
    }

    /**
     * Keys starting with "#" become section comments.
     *
     * @param  array<string, string>  $settings  Non-secret values for <code>.env.
     * @param  array<string, string>  $secrets  Secret values for <code>.env.secure.
     */
    public function write(string $code, array $settings, #[\SensitiveParameter] array $secrets): void
    {
        $directory = $this->directory($code);

        $this->files->ensureDirectoryExists($directory, 0750);

        $this->files->put($this->settingsPath($code), $this->render($settings, "Client {$code}: non-secret settings. Generated by edunexus:client:create."));
        $this->files->put($this->secretsPath($code), $this->render($secrets, "Client {$code}: secrets. Never commit or share this file."));

        $this->files->chmod($this->secretsPath($code), 0600);
    }

    public function read(string $code): Client
    {
        if (! $this->files->isFile($this->settingsPath($code)) || ! $this->files->isFile($this->secretsPath($code))) {
            throw new RuntimeException("Client [{$code}] not found in [{$this->root()}].");
        }

        $settings = Dotenv::parse($this->files->get($this->settingsPath($code)));
        $secrets = Dotenv::parse($this->files->get($this->secretsPath($code)));

        return new Client(
            code: $settings['EDUNEXUS_CLIENT_CODE'] ?? $code,
            name: $settings['EDUNEXUS_ORG_NAME'] ?? $code,
            type: InstitutionType::from($settings['EDUNEXUS_INSTITUTION_TYPE'] ?? ''),
            url: $settings['APP_URL'] ?? '',
            database: $secrets['DB_DATABASE'] ?? '',
            username: $secrets['DB_USERNAME'] ?? '',
            password: $secrets['DB_PASSWORD'] ?? '',
        );
    }

    /**
     * @return list<Client>
     */
    public function all(): array
    {
        if (! $this->files->isDirectory($this->root())) {
            return [];
        }

        $clients = [];

        foreach ($this->files->directories($this->root()) as $directory) {
            $code = basename($directory);

            if (preg_match(ClientEnvironment::CODE_PATTERN, $code) && $this->files->isFile($this->settingsPath($code))) {
                $clients[] = $this->read($code);
            }
        }

        return $clients;
    }

    public function delete(string $code): void
    {
        $this->files->deleteDirectory($this->directory($code));
    }

    /**
     * @param  array<string, string>  $values
     */
    private function render(array $values, string $header): string
    {
        $lines = ['# '.$header];

        foreach ($values as $key => $value) {
            if (str_starts_with($key, '#')) {
                array_push($lines, '', '# '.$value);

                continue;
            }

            $lines[] = $key.'='.$this->quote($value);
        }

        return implode("\n", $lines)."\n";
    }

    private function quote(string $value): string
    {
        if ($value === '' || preg_match('/^[A-Za-z0-9_.:\/@+=,-]+$/', $value)) {
            return $value;
        }

        return '"'.str_replace(['\\', '"', '$'], ['\\\\', '\\"', '\\$'], $value).'"';
    }
}
